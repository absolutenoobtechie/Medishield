"""
MediShield Runtime Security Gateway Dashboard
==============================================
This dashboard monitors runtime audit events generated by MediShield,
a security gateway situated between AI agents and simulated clinical backend tools.

All clinical data in this project is synthetic and designed for demonstration purposes.

Features:
- Reads live audit events from SQLite (`audit_events` table via server/db.py) or falls back
  to `logs/sample_events.jsonl`.
- Summary metric counters: Total Calls, Allowed, Blocked, Warnings.
- Interactive table of recent events with decision color-coding (green=allowed, red=blocked, amber=warning).
- Decision filtering via the sidebar.
- Detailed inspection panel displaying rule, reason, changed_fields, and state_changed.
- Manual data refresh button.
"""

import json
import sqlite3
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import pandas as pd
import streamlit as st

# ==============================================================================
# SECTION 1: Path Setup & Module Imports
# Plain Language Explanation:
# This section ensures that the project root directory is added to Python's
# module search path (`sys.path`). This allows us to cleanly import `server.db`
# regardless of whether Streamlit was launched from the repository root or
# from inside the dashboard directory.
# ==============================================================================
ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

try:
    from server.db import DEFAULT_DB_PATH, get_connection
except ImportError:
    # Graceful fallback if server.db is accessed in non-standard environments
    DEFAULT_DB_PATH = Path("medishield.sqlite3")

    def get_connection(db_path=DEFAULT_DB_PATH):
        conn = sqlite3.connect(str(db_path))
        conn.row_factory = sqlite3.Row
        return conn


# ==============================================================================
# SECTION 2: Data Loading Function (`load_events`)
# Plain Language Explanation:
# The `load_events()` function retrieves audit events from either the SQLite database
# or the JSON Lines log file:
# 1. It first checks the SQLite database (using `server/db.py`). If the `audit_events`
#    table exists and contains records, it loads and maps those rows into standard
#    audit event dictionaries without changing the contract format.
# 2. If the SQLite database is missing, empty, or uninitialized, it falls back to
#    reading synthetic events from `logs/sample_events.jsonl`.
# 3. This guarantees the dashboard works immediately out of the box with sample data
#    and seamlessly switches to live gateway executions once the database is populated.
# ==============================================================================
def load_events(db_path: Optional[Path] = None) -> List[Dict[str, Any]]:
    """
    Load audit events from the SQLite `audit_events` table if rows exist;
    otherwise fall back to reading `logs/sample_events.jsonl`.
    
    Returns:
        List of audit event dictionaries following the CONTRACT.md specification:
        - time (str)
        - request_id (str)
        - actor (str)
        - tool (str)
        - action_type (str)
        - approval_id (str or None)
        - decision (str: 'allowed', 'blocked', 'warning')
        - risk (str: 'low', 'medium', 'high')
        - rule (str)
        - reason (str)
        - changed_fields (list[str])
        - state_changed (bool)
    """
    events: List[Dict[str, Any]] = []
    target_db = Path(db_path) if db_path else (ROOT_DIR / DEFAULT_DB_PATH)

    # Attempt 1: Query SQLite database via server/db.py
    try:
        if target_db.exists():
            conn = get_connection(target_db)
            cursor = conn.cursor()
            # Verify table existence before querying
            cursor.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name='audit_events'"
            )
            if cursor.fetchone():
                cursor.execute("SELECT * FROM audit_events ORDER BY id DESC")
                rows = cursor.fetchall()
                if rows:
                    for row in rows:
                        # Normalize changed_fields (stored as TEXT in SQLite)
                        raw_cf = row["changed_fields"]
                        if isinstance(raw_cf, str):
                            try:
                                cf = json.loads(raw_cf)
                            except Exception:
                                cf = [f.strip() for f in raw_cf.split(",") if f.strip()]
                        elif isinstance(raw_cf, list):
                            cf = raw_cf
                        else:
                            cf = []

                        # Map actor column (actor_id in SQL table, actor in event contract)
                        actor = (
                            row["actor_id"]
                            if "actor_id" in row.keys()
                            else row.get("actor", "unknown")
                        )

                        event = {
                            "time": str(row["time"]),
                            "request_id": str(row["request_id"]),
                            "actor": str(actor),
                            "tool": str(row["tool"]),
                            "action_type": str(row["action_type"]),
                            "approval_id": row["approval_id"],
                            "decision": str(row["decision"]),
                            "risk": str(row["risk"]),
                            "rule": str(row["rule"]),
                            "reason": str(row["reason"]),
                            "changed_fields": cf,
                            "state_changed": bool(row["state_changed"]),
                        }
                        events.append(event)
                    conn.close()
                    return events
            conn.close()
    except Exception:
        # If any SQLite error occurs, cleanly fall through to JSONL fallback
        pass

    # Attempt 2: Fallback to synthetic logs/sample_events.jsonl
    jsonl_path = ROOT_DIR / "logs" / "sample_events.jsonl"
    if jsonl_path.exists():
        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        events.append(json.loads(line))
                    except Exception:
                        continue

    return events


# ==============================================================================
# SECTION 3: Streamlit UI Configuration & Header
# Plain Language Explanation:
# Sets the browser tab title and favicon, renders the top header banner with
# a title, subtitle, and a manual Refresh button that re-runs the script to fetch
# the freshest audit events.
# ==============================================================================
st.set_page_config(
    page_title="MediShield - Security Gateway Dashboard",
    page_icon="🛡️",
    layout="wide",
)

# Header layout with title on the left and manual Refresh button on the right
header_col1, header_col2 = st.columns([5, 1])
with header_col1:
    st.title("🛡️ MediShield Security Gateway")
    st.caption("Runtime security monitoring & audit logs for AI-connected clinical tools (Synthetic Data Only)")

with header_col2:
    st.write("")  # vertical spacing alignment
    if st.button("🔄 Refresh Data", key="top_refresh"):
        st.rerun()

# Load all events using the single load_events function
all_events = load_events()

# ==============================================================================
# SECTION 4: Sidebar Controls & Decision Filter
# Plain Language Explanation:
# The sidebar provides user controls:
# 1. A manual Refresh button to reload events from the data source.
# 2. A decision filter dropdown ('All', 'allowed', 'blocked', 'warning') to filter
#    the events shown in both the recent events table and the detail panel.
# 3. System status information displaying the active data source (SQLite vs. JSONL)
#    and total events loaded.
# ==============================================================================
st.sidebar.header("Gateway Controls")

# Manual Refresh button in the sidebar
if st.sidebar.button("🔄 Refresh", key="sidebar_refresh", use_container_width=True):
    st.rerun()

st.sidebar.divider()
st.sidebar.subheader("Filters")

# Filter by decision
decision_filter = st.sidebar.selectbox(
    "Filter by Decision:",
    options=["All", "allowed", "blocked", "warning"],
    index=0,
    help="Filter events in the dashboard by gateway decision."
)

# Determine active data source name for transparency
db_file = ROOT_DIR / DEFAULT_DB_PATH
source_label = "logs/sample_events.jsonl (fallback)"
if db_file.exists():
    try:
        conn = get_connection(db_file)
        c = conn.cursor()
        c.execute("SELECT count(*) FROM sqlite_master WHERE type='table' AND name='audit_events'")
        has_table = c.fetchone()[0] > 0
        if has_table:
            c.execute("SELECT count(*) FROM audit_events")
            sql_count = c.fetchone()[0]
            if sql_count > 0:
                source_label = "SQLite (audit_events table)"
        conn.close()
    except Exception:
        pass

st.sidebar.divider()
st.sidebar.caption(f"**Data Source:** `{source_label}`")
st.sidebar.caption(f"**Loaded Events:** {len(all_events)}")

# Filter the events based on the user's sidebar selection
if decision_filter == "All":
    filtered_events = list(all_events)
else:
    filtered_events = [e for e in all_events if e.get("decision") == decision_filter]

# ==============================================================================
# SECTION 5: Counters / Summary Metrics
# Plain Language Explanation:
# Calculates and displays aggregate security counters across all recorded events:
# - Total Calls: The grand total of AI tool calls monitored by the gateway.
# - Allowed: Calls that passed all policy, intent hash, and destination checks.
# - Blocked: Unauthorized, mismatched, or expired calls stopped by the gateway.
# - Warnings: Calls flagged with non-critical warnings (e.g., non-canonical units).
# These four metrics are displayed side-by-side using `st.columns` and `st.metric`.
# ==============================================================================
st.subheader("Gateway Activity Overview")

total_calls = len(all_events)
allowed_calls = sum(1 for e in all_events if e.get("decision") == "allowed")
blocked_calls = sum(1 for e in all_events if e.get("decision") == "blocked")
warning_calls = sum(1 for e in all_events if e.get("decision") == "warning")

metric_col1, metric_col2, metric_col3, metric_col4 = st.columns(4)
metric_col1.metric("Total Calls", total_calls)
metric_col2.metric("Allowed", allowed_calls)
metric_col3.metric("Blocked", blocked_calls)
metric_col4.metric("Warnings", warning_calls)

st.divider()

# ==============================================================================
# SECTION 6: Table of Recent Events with Decision Colors
# Plain Language Explanation:
# Displays the list of audit events in an interactive table using `st.dataframe`.
# A styling function is applied to the `decision` column to visually color-code
# each row:
# - Green: Allowed requests (safe and verified)
# - Red: Blocked requests (security violations or hash mismatches)
# - Amber: Warning requests (minor anomalies requiring attention)
# If a filter is applied in the sidebar, this table only displays the matching subset.
# ==============================================================================
st.subheader("Recent Audit Events")

if not filtered_events:
    st.info(f"No events found matching decision filter: '{decision_filter}'.")
else:
    # Convert filtered events to a DataFrame for tabular display
    df = pd.DataFrame(filtered_events)

    # Style function for decision color coding
    def color_decision(val):
        """Return CSS styling for decision cells."""
        val_str = str(val).lower()
        if val_str == "allowed":
            return "background-color: #d1e7dd; color: #0f5132; font-weight: bold;"
        elif val_str == "blocked":
            return "background-color: #f8d7da; color: #842029; font-weight: bold;"
        elif val_str == "warning":
            return "background-color: #fff3cd; color: #664d03; font-weight: bold;"
        return ""

    # Apply pandas Styler to highlight the decision column
    styler = df.style
    if hasattr(styler, "map"):
        styled_df = styler.map(color_decision, subset=["decision"])
    else:
        styled_df = styler.applymap(color_decision, subset=["decision"])

    st.dataframe(styled_df, use_container_width=True)

st.divider()

# ==============================================================================
# SECTION 7: Detail Panel for a Selected Event
# Plain Language Explanation:
# Provides a deep-dive inspection panel for any selected event.
# The user selects an event from the dropdown, and this section highlights:
# 1. Rule: The exact gateway rule that triggered the decision.
# 2. Reason: Plain-language explanation of why the action was permitted or stopped.
# 3. Changed Fields: The list of protected action fields that differed or changed.
# 4. State Changed: Whether the clinical backend database state was modified.
# In addition, contextual metadata (Request ID, Actor, Tool, Approval ID, Risk)
# and the full raw event JSON are displayed for thorough clinical auditability.
# ==============================================================================
st.subheader("Event Detail Panel")

if filtered_events:
    # Build readable options for the selection dropdown
    event_options = [
        f"#{idx + 1} | [{event.get('decision', '').upper()}] {event.get('request_id', '')} — {event.get('tool', '')} ({event.get('time', '')})"
        for idx, event in enumerate(filtered_events)
    ]

    selected_index = st.selectbox(
        "Select an audit event to inspect details:",
        options=range(len(filtered_events)),
        format_func=lambda i: event_options[i],
    )
    selected_event = filtered_events[selected_index]

    # Display primary required fields in two columns
    detail_col1, detail_col2 = st.columns(2)

    with detail_col1:
        st.markdown("**Security Rule:**")
        st.code(selected_event.get("rule", "N/A"), language="text")

        st.markdown("**Backend State Changed:**")
        state_bool = selected_event.get("state_changed", False)
        if state_bool:
            st.markdown("`True` *(Database state modified)*")
        else:
            st.markdown("`False` *(No changes committed)*")

    with detail_col2:
        st.markdown("**Plain-Language Reason:**")
        st.info(selected_event.get("reason", "No reason provided."))

        st.markdown("**Changed Fields:**")
        changed = selected_event.get("changed_fields", [])
        if changed:
            st.warning(f"`{changed}`")
        else:
            st.success("`[]` *(No protected fields changed)*")

    # Display secondary metadata in four metric columns
    st.caption("Event Metadata")
    meta1, meta2, meta3, meta4 = st.columns(4)
    meta1.metric("Request ID", selected_event.get("request_id", "N/A"))
    meta2.metric("Actor", selected_event.get("actor", "N/A"))
    meta3.metric("Tool", selected_event.get("tool", "N/A"))
    meta4.metric("Approval ID", str(selected_event.get("approval_id") or "None"))

    # Display raw event JSON for full audit fidelity
    st.caption("Raw Audit Event Record")
    st.json(selected_event)
else:
    st.info("No events available to display in the detail panel.")
